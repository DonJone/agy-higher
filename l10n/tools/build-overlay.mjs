#!/usr/bin/env node
/**
 * AgyHigher STE-STC Overlay Compiler
 * Compiles l10n/src/dict/*.json + l10n/src/runtime/{rules,engine}.js into:
 *   - l10n/dist/antigravity-stc-overlay.js (self-contained non-destructive DOM IIFE)
 *   - l10n/dist/manifest.json
 *
 * Flags:
 *   --check                        Verify committed dist files are up-to-date (no write)
 *   --out <dir>                    Write compiled overlay & manifest to custom output dir
 *   --custom <file>                Bake custom-translations.txt prelude into output overlay
 *   --keep-english-options <bool>  Set default keepEnglishOptionNames flag (default: true)
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'src');
const DICT_DIR = path.join(SRC_DIR, 'dict');
const RUNTIME_DIR = path.join(SRC_DIR, 'runtime');
const GLOSSARY_PATH = path.join(SRC_DIR, 'ste-stc-glossary.json');
const DEFAULT_OUT_DIR = path.join(ROOT, 'dist');

const MAX_CUSTOM_BYTES = 64 * 1024;
const MAX_CUSTOM_ENTRIES = 2000;

export function parseCustomTranslationsText(text) {
  if (!text || typeof text !== 'string') return [];
  const entries = [];
  const seen = new Map();
  const lines = text.split(/\r?\n/);

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;

    const eqIdx = line.indexOf('=');
    let src = '';
    let dst = '';
    if (eqIdx === -1) {
      src = line;
      dst = ''; // Keep original English
    } else {
      src = line.slice(0, eqIdx).trim();
      dst = line.slice(eqIdx + 1).trim();
    }
    if (!src) continue;
    const key = src.toLowerCase();
    if (seen.has(key)) {
      entries[seen.get(key)] = [src, dst];
    } else {
      if (entries.length >= MAX_CUSTOM_ENTRIES) break;
      seen.set(key, entries.length);
      entries.push([src, dst]);
    }
  }
  return entries;
}

export function loadMergedPhrases() {
  const files = fs
    .readdirSync(DICT_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const domains = {};
  const map = new Map();

  for (const file of files) {
    const domain = file.replace(/\.json$/, '');
    const raw = JSON.parse(fs.readFileSync(path.join(DICT_DIR, file), 'utf8'));
    const obj = raw && typeof raw === 'object' && raw.phrases && typeof raw.phrases === 'object'
      ? raw.phrases
      : raw;
    domains[domain] = Object.keys(obj).length;
    for (const [k, v] of Object.entries(obj)) {
      const src = k.trim();
      const dst = String(v).trim();
      if (!src || !dst) continue;
      map.set(src.toLowerCase(), [src, dst]);
    }
  }

  const phrases = Array.from(map.values()).sort((a, b) => {
    if (b[0].length !== a[0].length) return b[0].length - a[0].length;
    return a[0].localeCompare(b[0], 'en');
  });
  return { phrases, domains };
}

function stripExports(jsCode) {
  return jsCode
    .replace(/^\s*export\s+(const|let|var|function)\s+/gm, '$1 ')
    .trim();
}

export function compileOverlay({
  customEntries = [],
  keepEnglishOptionNames = true
} = {}) {
  const glossary = JSON.parse(fs.readFileSync(GLOSSARY_PATH, 'utf8'));
  const { phrases, domains } = loadMergedPhrases();
  const rulesSrc = stripExports(
    fs.readFileSync(path.join(RUNTIME_DIR, 'rules.js'), 'utf8')
  );
  const engineSrc = stripExports(
    fs.readFileSync(path.join(RUNTIME_DIR, 'engine.js'), 'utf8')
  );

  const bundlePayload = `/*
 * AgyHigher STE-STC Chinese Localization Overlay
 * Standard: ${glossary.standard}
 * Target Antigravity Version: ${glossary.version}
 * Generated by l10n/tools/build-overlay.mjs (DO NOT HAND-EDIT)
 * Non-destructive DOM overlay inspired by yuexps/Antigravity-Hans.
 */
(function () {
  'use strict';
  if (typeof window === 'undefined') return;
  if (typeof window.__AGY_HIGHER_STC_CLEANUP__ === 'function') {
    try {
      window.__AGY_HIGHER_STC_CLEANUP__();
    } catch (_e) {}
  }
  window.__AGY_HIGHER_STC_OVERLAY_LOADED__ = true;

  var DEFAULT_CONFIG = ${JSON.stringify({
    version: glossary.version,
    standard: glossary.standard,
    keepEnglishOptionNames: Boolean(keepEnglishOptionNames)
  })};

  var BAKED_CUSTOM_ENTRIES = ${JSON.stringify(customEntries)};
  var PHRASES = ${JSON.stringify(phrases, null, 2)};

  ${rulesSrc}

  ${engineSrc}

  function resolveConfig() {
    var ext = window.__antigravityStcConfig || {};
    var custom = Array.isArray(window.__antigravityZhCustom)
      ? BAKED_CUSTOM_ENTRIES.concat(window.__antigravityZhCustom)
      : BAKED_CUSTOM_ENTRIES;
    return {
      phrases: PHRASES,
      customEntries: custom,
      keepEnglishOptionNames:
        typeof ext.keepEnglishOptionNames === 'boolean'
          ? ext.keepEnglishOptionNames
          : DEFAULT_CONFIG.keepEnglishOptionNames,
      keepOptionSet: KEEP_ENGLISH_OPTION_NAMES,
      permissionTemplates: PERMISSION_TEMPLATES,
      dynamicPatterns: DYNAMIC_PATTERNS
    };
  }

  var enabled = true;
  try {
    var saved = window.localStorage.getItem('agy_higher_stc_enabled');
    if (saved === '0') enabled = false;
  } catch (_e) {}

  var translator = createTranslator(resolveConfig());
  var originalTextMap = new WeakMap();
  var originalAttrMap = new WeakMap();
  var trackedTextNodes = new Set();
  var trackedAttrElements = new Set();
  var ATTRS = ['placeholder', 'title', 'aria-label'];
  var activeObserver = null;

  function shouldSkipElement(el) {
    if (!el || el.nodeType !== 1) return false;
    if (el.id === 'agy-higher-stc-toggle') return true;
    try {
      return Boolean(el.closest && el.closest(SKIP_DOM_SELECTOR));
    } catch (_e) {
      return false;
    }
  }

  function processTextNode(node) {
    if (!node || node.nodeType !== 3) return;
    if (shouldSkipElement(node.parentElement)) return;
    var cur = node.nodeValue;
    if (!cur || !cur.trim()) return;

    if (!enabled) {
      if (originalTextMap.has(node)) {
        var orig = originalTextMap.get(node);
        if (node.nodeValue !== orig) node.nodeValue = orig;
      }
      return;
    }

    var source = originalTextMap.has(node) ? originalTextMap.get(node) : cur;
    var translated = translator.translate(source);
    if (translated !== source) {
      if (!originalTextMap.has(node)) {
        originalTextMap.set(node, source);
        trackedTextNodes.add(node);
      }
      if (node.nodeValue !== translated) node.nodeValue = translated;
    }
  }

  function processElementAttrs(el) {
    if (!el || el.nodeType !== 1 || shouldSkipElement(el)) return;
    var saved = originalAttrMap.get(el);
    for (var i = 0; i < ATTRS.length; i++) {
      var attr = ATTRS[i];
      if (!el.hasAttribute(attr)) continue;
      var val = el.getAttribute(attr);
      if (!val || !val.trim()) continue;
      if (!enabled) {
        if (saved && Object.prototype.hasOwnProperty.call(saved, attr)) {
          if (val !== saved[attr]) el.setAttribute(attr, saved[attr]);
        }
        continue;
      }
      var source = saved && Object.prototype.hasOwnProperty.call(saved, attr) ? saved[attr] : val;
      var translated = translator.translate(source);
      if (translated !== source) {
        if (!saved) {
          saved = {};
          originalAttrMap.set(el, saved);
          trackedAttrElements.add(el);
        }
        if (!Object.prototype.hasOwnProperty.call(saved, attr)) saved[attr] = source;
        if (val !== translated) el.setAttribute(attr, translated);
      }
    }
  }

  function restoreAllTracked() {
    trackedTextNodes.forEach(function (node) {
      try {
        if (originalTextMap.has(node)) {
          var orig = originalTextMap.get(node);
          if (node.nodeValue !== orig) node.nodeValue = orig;
        }
      } catch (_e) {}
    });
    trackedAttrElements.forEach(function (el) {
      try {
        var saved = originalAttrMap.get(el);
        if (!saved) return;
        for (var i = 0; i < ATTRS.length; i++) {
          var attr = ATTRS[i];
          if (Object.prototype.hasOwnProperty.call(saved, attr)) {
            el.setAttribute(attr, saved[attr]);
          }
        }
      } catch (_e) {}
    });
    trackedTextNodes.clear();
    trackedAttrElements.clear();
  }

  function walkTree(root) {
    if (!root) return;
    if (root.nodeType === 3) {
      processTextNode(root);
      return;
    }
    if (root.nodeType === 1) {
      if (shouldSkipElement(root)) return;
      processElementAttrs(root);
    }
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    var cur = walker.nextNode();
    while (cur) {
      if (cur.nodeType === 3) {
        processTextNode(cur);
      } else if (cur.nodeType === 1) {
        processElementAttrs(cur);
      }
      cur = walker.nextNode();
    }
  }

  function mountToggle() {
    if (!document.body || document.getElementById('agy-higher-stc-toggle')) return;
    var btn = document.createElement('button');
    btn.id = 'agy-higher-stc-toggle';
    btn.type = 'button';
    btn.textContent = enabled ? 'ZH' : 'EN';
    btn.title = 'AgyHigher STE-STC 中文拓展开关';
    btn.style.cssText = [
      'position:fixed',
      'right:12px',
      'bottom:12px',
      'z-index:2147483647',
      'height:24px',
      'padding:0 8px',
      'border-radius:5px',
      'border:1px solid rgba(255,255,255,0.08)',
      'background:rgba(16,16,18,0.88)',
      'color:#EDEDEF',
      'font:600 11px/22px -apple-system,BlinkMacSystemFont,sans-serif',
      'cursor:pointer',
      'letter-spacing:0.04em'
    ].join(';');
    btn.addEventListener('click', function () {
      enabled = !enabled;
      try {
        window.localStorage.setItem('agy_higher_stc_enabled', enabled ? '1' : '0');
      } catch (_e) {}
      btn.textContent = enabled ? 'ZH' : 'EN';
      walkTree(document.body);
    });
    document.body.appendChild(btn);
  }

  var scheduled = false;
  var pendingRoots = new Set();
  function flushMutations() {
    scheduled = false;
    pendingRoots.forEach(function (node) {
      walkTree(node);
    });
    pendingRoots.clear();
  }

  function start() {
    if (!document.body) return;
    walkTree(document.body);
    mountToggle();
    activeObserver = new MutationObserver(function (mutations) {
      for (var i = 0; i < mutations.length; i++) {
        var m = mutations[i];
        if (m.type === 'characterData' && m.target) {
          pendingRoots.add(m.target);
        } else if (m.type === 'attributes' && m.target) {
          pendingRoots.add(m.target);
        } else if (m.addedNodes && m.addedNodes.length) {
          for (var j = 0; j < m.addedNodes.length; j++) {
            pendingRoots.add(m.addedNodes[j]);
          }
        }
      }
      if (!scheduled && pendingRoots.size > 0) {
        scheduled = true;
        requestAnimationFrame(flushMutations);
      }
    });
    activeObserver.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRS
    });
  }

  window.__AGY_HIGHER_STC_CLEANUP__ = function () {
    if (activeObserver) {
      activeObserver.disconnect();
      activeObserver = null;
    }
    enabled = false;
    restoreAllTracked();
    var btn = document.getElementById('agy-higher-stc-toggle');
    if (btn && btn.parentNode) btn.parentNode.removeChild(btn);
    window.__AGY_HIGHER_STC_OVERLAY_LOADED__ = false;
  };

  window.__AGY_HIGHER_STC_API__ = {
    version: DEFAULT_CONFIG.version,
    standard: DEFAULT_CONFIG.standard,
    phraseCount: PHRASES.length,
    translate: function (s) {
      return translator.translate(s);
    },
    setEnabled: function (flag) {
      enabled = Boolean(flag);
      var btn = document.getElementById('agy-higher-stc-toggle');
      if (btn) btn.textContent = enabled ? 'ZH' : 'EN';
      walkTree(document.body);
    },
    cleanup: window.__AGY_HIGHER_STC_CLEANUP__
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start, { once: true });
  } else {
    start();
  }
})();
`;

  const sha256 = crypto.createHash('sha256').update(bundlePayload, 'utf8').digest('hex');
  const manifest = {
    version: glossary.version,
    standard: glossary.standard,
    phraseCount: phrases.length,
    customEntryCount: customEntries.length,
    keepEnglishOptionNames: Boolean(keepEnglishOptionNames),
    domains,
    sha256
  };
  return { bundlePayload, manifest };
}

function parseCliArgs(argv) {
  const opts = {
    check: false,
    outDir: DEFAULT_OUT_DIR,
    customPath: null,
    keepEnglishOptionNames: true
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      opts.check = true;
    } else if (arg === '--out' && argv[i + 1]) {
      opts.outDir = path.resolve(argv[++i]);
    } else if (arg === '--custom' && argv[i + 1]) {
      opts.customPath = path.resolve(argv[++i]);
    } else if (arg === '--keep-english-options' && argv[i + 1]) {
      opts.keepEnglishOptionNames = argv[++i] !== 'false';
    }
  }
  return opts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseCliArgs(process.argv.slice(2));
  let customEntries = [];
  if (opts.customPath && fs.existsSync(opts.customPath)) {
    const stat = fs.statSync(opts.customPath);
    if (stat.size <= MAX_CUSTOM_BYTES) {
      customEntries = parseCustomTranslationsText(fs.readFileSync(opts.customPath, 'utf8'));
    }
  }

  const { bundlePayload, manifest } = compileOverlay({
    customEntries,
    keepEnglishOptionNames: opts.keepEnglishOptionNames
  });

  const overlayPath = path.join(opts.outDir, 'antigravity-stc-overlay.js');
  const manifestPath = path.join(opts.outDir, 'manifest.json');
  const manifestText = JSON.stringify(manifest, null, 2) + '\n';

  if (opts.check) {
    const curOverlay = fs.existsSync(overlayPath) ? fs.readFileSync(overlayPath, 'utf8') : '';
    const curManifest = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, 'utf8') : '';
    if (curOverlay !== bundlePayload || curManifest !== manifestText) {
      console.error('[ERROR] l10n/dist is out of sync with l10n/src. Run: node l10n/tools/build-overlay.mjs');
      process.exit(1);
    }
    console.log(
      `[OK] l10n/dist is in sync (${manifest.phraseCount} phrases, v${manifest.version}, sha256:${manifest.sha256.slice(0, 12)})`
    );
    process.exit(0);
  }

  fs.mkdirSync(opts.outDir, { recursive: true });
  fs.writeFileSync(overlayPath, bundlePayload, 'utf8');
  fs.writeFileSync(manifestPath, manifestText, 'utf8');
  console.log(
    `[BUILD] Wrote ${overlayPath} (${manifest.phraseCount} phrases, ${manifest.customEntryCount} custom rules, sha256:${manifest.sha256.slice(0, 12)})`
  );
}
